"""Ingest regulation documents into PostgreSQL.

Usage (run by the operator against a reachable database and Vertex AI):

    python -m nutrilens_api.rag.ingest --manifest data/regulations/manifest.json \\
        [--additives data/additives.csv]

The manifest is a JSON list. Each entry names a file that was downloaded
unchanged from the official source:

    {"id": "...", "title": "...", "issuer": "...", "version": "...",
     "source_url": "...", "file": "relative/path.pdf"}

`file` is resolved relative to the manifest. `.pdf` and `.txt` are supported.
The SHA-256 of each file is stored so a later reader can confirm which bytes
were ingested. No regulation text is ever generated by this program.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

from pypdf import PdfReader

from ..config import Settings
from ..llm import LlmClient
from .additives import load_additives
from .chunker import Chunk, chunk_document
from .store import DocumentRecord, Store

_REQUIRED = ("id", "title", "issuer", "version", "source_url", "file")


class ManifestError(ValueError):
    pass


def load_manifest(path: Path) -> list[dict]:
    entries = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(entries, list) or not entries:
        raise ManifestError("manifest must be a non-empty JSON list")
    seen: set[str] = set()
    for position, entry in enumerate(entries, start=1):
        if not isinstance(entry, dict):
            raise ManifestError(f"entry {position} is not an object")
        for key in _REQUIRED:
            if not isinstance(entry.get(key), str) or not entry[key].strip():
                raise ManifestError(f"entry {position}: '{key}' is required")
        if entry["id"] in seen:
            raise ManifestError(f"duplicate id {entry['id']}")
        seen.add(entry["id"])
    return entries


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def read_text(path: Path) -> str:
    suffix = path.suffix.lower()
    if suffix == ".txt":
        return path.read_text(encoding="utf-8")
    if suffix == ".pdf":
        reader = PdfReader(str(path))
        return "\n".join((page.extract_text() or "") for page in reader.pages)
    raise ManifestError(f"unsupported file type: {suffix}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Ingest regulation documents")
    parser.add_argument("--manifest", required=True, type=Path)
    parser.add_argument("--additives", type=Path, default=None)
    args = parser.parse_args(argv)

    settings = Settings.from_env()
    store = Store(settings.db_conninfo(), settings.embedding_dim)
    llm = LlmClient(settings)
    store.init_schema()

    manifest = load_manifest(args.manifest)
    base = args.manifest.parent
    all_chunks: list[Chunk] = []

    for entry in manifest:
        file_path = (base / entry["file"]).resolve()
        if not file_path.is_file():
            print(f"missing file for {entry['id']}: {entry['file']}", file=sys.stderr)
            return 2
        text = read_text(file_path)
        chunks = chunk_document(entry["id"], text)
        if not chunks:
            print(f"no text extracted from {entry['file']} (scanned PDF?)", file=sys.stderr)
            return 2
        vectors = llm.embed([f"[{c.locator}] {c.text}" for c in chunks], "RETRIEVAL_DOCUMENT")
        store.upsert_document(
            DocumentRecord(
                doc_id=entry["id"],
                title=entry["title"],
                issuer=entry["issuer"],
                version=entry["version"],
                source_url=entry["source_url"],
                sha256=sha256_of(file_path),
            )
        )
        store.replace_chunks(entry["id"], list(zip(chunks, vectors, strict=True)))
        all_chunks.extend(chunks)
        print(f"{entry['id']}: {len(chunks)} chunks")

    if args.additives is not None:
        records = load_additives(args.additives, {e["id"] for e in manifest}, all_chunks)
        store.upsert_additives(records)
        print(f"additives: {len(records)} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
